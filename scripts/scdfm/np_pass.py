"""scDFM's L2 the way the tables read it: N_p predicted cells per condition (scDFM eq. 15).

    python scripts/scdfm/np_pass.py --name v1 --gpus 0 1 2 3

then one tmux pane per printed queue. Each queue re-predicts chosen checkpoints of a
finished scdfm_queue.py run with SCDFM_TEST_ONLY and SCDFM_PRED_CELLS=0 - as many cells as
each condition has, where the training-time predictions used 128 - and scores them with
score_scdfm.py, so the L2 column of <family>_np/scpkr2_scores_<block>.csv is on the same
footing as scPKR2's (arm_table.py's L2 uses N_p soft cells).

WHICH CHECKPOINTS. For every block, the one with the best L2 at 128 cells, and the last.
Every checkpoint at N_p would cost about ten times the training-time predictions. The other
five columns stay where the tables read them, at 128 cells.

Same patch, split, tag, bf16 and batch as training: the checkpoint is loaded through
--checkpoint_path and scored once (scripts/scdfm/scdfm_val.patch, SCDFM_TEST_ONLY).
"""

from __future__ import annotations

import argparse
import csv
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scdfm_queue import FAMILIES, env, run_args  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def chosen(result: str, blocks: list[str]) -> list[int]:
    picks = set()
    for block in blocks:
        path = os.path.join(result, f"scpkr2_scores_{block}.csv")
        with open(path, newline="", encoding="utf-8") as handle:
            rows = list(csv.DictReader(handle))
        if not rows:
            raise SystemExit(f"{path} is empty")
        picks.add(int(min(rows, key=lambda r: float(r["L2"]))["iteration"]))
        picks.add(max(int(r["iteration"]) for r in rows))
    return sorted(picks)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", required=True, help="the scdfm_queue.py run to re-predict")
    parser.add_argument("--scdfm-dir", default="/mnt/data/dev/scDFM")
    parser.add_argument("--gpus", nargs="+", default=["0", "1", "2", "3"])
    parser.add_argument("--threads", type=int, default=16)
    args = parser.parse_args()
    os.chdir(ROOT)
    split_dir = os.path.join(ROOT, "results", "scdfm", "splits")

    jobs = []  # (family, iteration, checkpoint)
    for family, (_, _, blocks, _) in FAMILIES.items():
        result = os.path.join(args.scdfm_dir, "result", args.name, family)
        if not os.path.isdir(result):
            print(f"  {family}: no run under {result}, skipped")
            continue
        for iteration in chosen(result, blocks):
            found = glob.glob(os.path.join(result, "*", f"iteration_{iteration}", "checkpoint.pt"))
            if len(found) != 1:
                raise SystemExit(f"{family} iteration {iteration}: {len(found)} checkpoints")
            jobs.append((family, iteration, found[0]))

    # A family's checkpoints stay on one queue, so two queues never score the same folder.
    # Rough cost per checkpoint: conditions x cells, ComboSciPlex conditions holding about
    # eight times Norman's cells.
    queues: list[list[tuple]] = [[] for _ in args.gpus]
    load = [0.0] * len(args.gpus)
    by_family: dict[str, list[tuple]] = {}
    for job in jobs:
        by_family.setdefault(job[0], []).append(job)

    def cost(family: str) -> float:
        data_name, _, _, conditions = FAMILIES[family]
        return len(by_family[family]) * conditions * (8 if data_name == "combosciplex" else 1)

    for family in sorted(by_family, key=cost, reverse=True):
        index = min(range(len(queues)), key=lambda i: load[i])
        queues[index] += by_family[family]
        load[index] += cost(family)

    out_dir = os.path.join("results", "scdfm", args.name)
    os.makedirs(out_dir, exist_ok=True)
    for gpu, mine in zip(args.gpus, queues):
        lines = ["#!/bin/sh", f"# Generated by scripts/scdfm/np_pass.py. GPU {gpu}.",
                 "set -e", 'cd "$(dirname "$0")/../../.."', ""]
        families = []
        for family, iteration, checkpoint in mine:
            target = f"{args.scdfm_dir}/result/{args.name}/{family}_np/iteration_{iteration}"
            lines += [f'echo "=== {family} iteration {iteration}, N_p cells ==="',
                      f'if [ ! -f "{target}/pred.h5ad" ]; then',
                      f"  SCDFM_TEST_ONLY={target} SCDFM_PRED_CELLS=0 SCDFM_NO_EVAL=1 "
                      f"ACCELERATE_MIXED_PRECISION=bf16 CUDA_VISIBLE_DEVICES={gpu} "
                      f"{env(family, split_dir)} env -C {args.scdfm_dir} .venv/bin/python "
                      f"{run_args(family, 200000, 20000, args.name + '_np')} "
                      f"--checkpoint_path={checkpoint}",
                      "fi", ""]
            if family not in families:
                families.append(family)
        for family in families:
            blocks = " ".join(FAMILIES[family][2])
            lines += [f"python scripts/scdfm/score_scdfm.py "
                      f"{args.scdfm_dir}/result/{args.name}/{family}_np --blocks {blocks} "
                      f"--threads {args.threads}"]
        lines += ['echo "=== queue done ==="', ""]
        path = os.path.join(out_dir, f"np_gpu{gpu}.sh")
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(lines))
        os.chmod(path, 0o755)
        print(f"  sh {path}   ({len(mine)} checkpoints: "
              + ", ".join(f"{f}@{i}" for f, i, _ in mine) + ")")


if __name__ == "__main__":
    main()
